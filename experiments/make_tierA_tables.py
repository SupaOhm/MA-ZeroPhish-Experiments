"""Regenerate the "Current results" tables of the Exp 2 and Exp 5 READMEs from the result
files (never typed by hand). Copies runs/exp2/phase1_{dev,test}.json and
runs/exp5/audit_{dev,test}.json into each experiment's results/ with a DATA_VERSION suffix
and replaces the README section starting "## Current results" up to the next "## ".

    python experiments/make_tierA_tables.py <DATA_VERSION>
"""
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def exp2_table(dv: str, path: Path) -> str:
    r2 = json.loads(path.read_text(encoding="utf-8"))["results"]
    out = [f"## Current results — DATA_VERSION `{dv}` (own-domain selection, CT v2; frozen Phase 1 unchanged)",
           f"Generated by `experiments/make_tierA_tables.py` from `results/{path.name}`. Sections marked",
           "superseded below are on earlier data versions.", "",
           "| condition / budget | arm | specialists / object | modality cov. at dispatch | trigger cov. (literal / all-fields) | est. tokens / case | Δ tokens vs fixed [95% CI] | saving |",
           "|---|---|---|---|---|---|---|---|"]
    for key in ("complete/unrestricted", "partial_browser/unrestricted",
                "no_network_metadata/unrestricted", "complete/matched_agent_2"):
        r = r2[key]
        for arm, name in (("fixed_all", "fixed_all"), ("adaptive", "adaptive (literal eq.10)"),
                          ("adaptive_all_fields", "adaptive_all_fields (MA-ZeroPhish)")):
            a = r[arm]
            d = r.get(f"paired_diff_{arm}_minus_fixed_tokens")
            sav = r.get(f"initial_token_saving_fraction_{arm}")
            out.append(
                f"| {key if arm == 'fixed_all' else ''} | {name} | {a['mean_specialists_dispatched_per_object']:.2f} | "
                f"{a['mean_modality_coverage_at_dispatch']:.2f} | {a['mean_trigger_coverage']:.2f} / "
                f"{a['mean_trigger_coverage_all_fields']:.2f} | {a['mean_initial_est_tokens_per_case']:,.0f} | "
                + (f"{d['mean']:,.0f} [{d['ci95'][0]:,.0f}, {d['ci95'][1]:,.0f}]" if d else "—") + " | "
                + (f"{sav:.0%}" if sav is not None else "—") + " |")
    bl = r2["complete/unrestricted"]["adaptive_all_fields"]["by_label"]
    out += ["", f"By class (complete): triggers per object phishing {bl['phishing']['mean_triggers_per_object']} "
            f"vs benign {bl['benign']['mean_triggers_per_object']}; the all-fields arm dispatches "
            f"{bl['phishing']['mean_specialists_dispatched_per_object']} (phishing) vs "
            f"{bl['benign']['mean_specialists_dispatched_per_object']} (benign) specialists per object.", ""]
    return "\n".join(out) + "\n"


def exp5_table(dv: str, path: Path) -> str:
    r5 = json.loads(path.read_text(encoding="utf-8"))["results"]
    out = [f"## Current results — DATA_VERSION `{dv}` (own-domain selection, CT v2; Metadata requires CT)",
           f"Generated by `experiments/make_tierA_tables.py` from `results/{path.name}`. Sections marked",
           "superseded below are on earlier data versions.", "",
           "| condition | cases | withholding violations | analyzable / 4 | coverage ceiling | verdict possible | lost vs base | gaps to disclose | acquisition attempts | recovery |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for k, r in r5.items():
        if isinstance(r, str):
            continue
        out.append(f"| {k} | {r['cases']} | {r['violations']} | {r['mean_analyzable_agents']:.2f} | "
                   f"{r['mean_coverage_ceiling']:.2f} | {r['substantive_verdict_possible']:.1%} | "
                   f"{r['lost_vs_base']} | {r['mean_gaps_to_disclose']:.2f} | {r['mean_acquisition_attempts']:.1f} | "
                   + (f"{r['recovery_rate']:.1%}" if r['recovery_rate'] is not None else "—") + " |")
    bl = r5["cum3_+html_no_browser"]["by_label"]
    out += ["", f"No browser capture: a substantive verdict remains possible for "
            f"{bl['phishing']['substantive_verdict_possible']:.0%} of phishing vs "
            f"{bl['benign']['substantive_verdict_possible']:.0%} of benign test cases (URL + CT are two fields; "
            "cases with no certificate covering the host before observation fall below the 2-field minimum).", ""]
    return "\n".join(out) + "\n"


def replace_current(readme: Path, table: str) -> None:
    s = readme.read_bytes().decode("utf-8").replace("\r\n", "\n")
    m = re.search(r"^## Current results.*?(?=^## )", s, flags=re.S | re.M)
    if m:
        old = m.group(0)
        old_dv = re.search(r"`([0-9a-f]{16})`", old)
        superseded = old.replace("## Current results", "## (Superseded, earlier data version) Results", 1)
        s = s.replace(old, table + "\n" + (superseded if old_dv else ""), 1)
    else:
        raise SystemExit(f"no 'Current results' section in {readme}")
    readme.write_bytes(s.encode("utf-8"))


def main() -> None:
    dv = sys.argv[1]
    e2, e5 = ROOT / "experiments" / "exp2_selection", ROOT / "experiments" / "exp5_robustness"
    for split in ("dev", "test"):
        shutil.copyfile(ROOT / "runs" / "exp2" / f"phase1_{split}.json", e2 / "results" / f"phase1_{split}__{dv}.json")
        shutil.copyfile(ROOT / "runs" / "exp5" / f"audit_{split}.json", e5 / "results" / f"audit_{split}__{dv}.json")
    replace_current(e2 / "README.md", exp2_table(dv, e2 / "results" / f"phase1_test__{dv}.json"))
    replace_current(e5 / "README.md", exp5_table(dv, e5 / "results" / f"audit_test__{dv}.json"))
    print("updated both READMEs for", dv)


if __name__ == "__main__":
    main()
