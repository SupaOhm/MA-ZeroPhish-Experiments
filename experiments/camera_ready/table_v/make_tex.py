"""Write the camera-ready Table V LaTeX snippets from the stored results (no number is typed by hand).

    python experiments/camera_ready/table_v/make_tex.py   # -> experiments/camera_ready/table_v/table_v.tex
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
RES = json.loads((HERE / "results" / "table_v_matched_recall.json").read_text(encoding="utf-8"))
YIELD = json.loads((ROOT / "experiments" / "results_gpt4omini" / "exp4_escalation" / "test3.json")
                   .read_text(encoding="utf-8"))
ROWS = [("full_collaboration", "Full-agent collaboration", "test3:full_debate"),
        ("targeted_collaboration", "Targeted collaboration", "test3:mazerophish"),
        ("no_collaboration", "No collaboration", None)]


def f3(x):
    return f"{x:.3f}"


def main() -> None:
    r = RES["rows"]
    main_rows, extra_rows = [], []
    for key, name, ykey in ROWS:
        d = r[key]
        op = d["frozen_operating_point"]
        yld = f3(YIELD[ykey]["escalation_precision"]) if ykey else "--"
        main_rows.append(f"{name} & {f3(op['f1'])} & {f3(op['fpr'])} & {f3(d['at_recall']['0.870']['fpr'])} & "
                         f"{f3(d['at_recall']['0.900']['fpr'])} & {d['cost_per_page']['model_calls']:.2f} & {yld} \\\\")
        c = d["cost_per_page"]
        extra_rows.append(f"{name} & {f3(d['pr_auc'])} & {f3(d['roc_auc'])} & {f3(d['at_fpr']['0.010']['tpr'])} & "
                          f"{c['input_tokens'] / 1000:.1f}k & {c['output_tokens'] / 1000:.1f}k & "
                          f"{c['usd_per_1000_pages']:.2f} \\\\")
    price = RES["price"]
    tex = rf"""% Generated by experiments/camera_ready/table_v/make_tex.py from results/table_v_matched_recall.json.
% Captions are placeholders for the paper's author to rewrite.
\begin{{table}}[t]
\centering
\caption{{Collaboration policies on the 1,000-object test split. FPR$_{{R}}$: false-positive rate with each
policy's threshold set to recall $R$ (post-hoc; the frozen operating point is unchanged).}}
\label{{tab:collaboration}}
\setlength{{\tabcolsep}}{{3pt}}
\begin{{tabular}}{{lcccccc}}
\toprule
Policy & F1 & FPR & FPR$_{{.87}}$ & FPR$_{{.90}}$ & Calls & Yield \\
\midrule
{chr(10).join(main_rows)}
\bottomrule
\end{{tabular}}
\end{{table}}

% Optional second table (extra metrics that do not fit Table V).
\begin{{table}}[t]
\centering
\caption{{Threshold-free accuracy and cost of the collaboration policies (test split). Tokens per object;
USD per 1,000 objects at \${price['input'] * 1e6:.2f}/\${price['output'] * 1e6:.2f} per million input/output
tokens (OpenRouter, {price['checked']}).}}
\label{{tab:collaboration-cost}}
\setlength{{\tabcolsep}}{{3pt}}
\begin{{tabular}}{{lcccccc}}
\toprule
Policy & PR-AUC & ROC-AUC & TPR$_{{1\%}}$ & In & Out & USD \\
\midrule
{chr(10).join(extra_rows)}
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    (HERE / "table_v.tex").write_text(tex, encoding="utf-8")
    print(tex)


if __name__ == "__main__":
    main()
